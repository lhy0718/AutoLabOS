export const REQUIRED_CONFIRMATORY_MUTATION_FAMILIES = [
  "comparison_evidence_gap",
  "repeated_run_provenance_gap",
  "hidden_failed_execution",
  "executed_budget_mismatch",
  "result_figure_conflict",
  "claim_evidence_conflict",
  "citation_support_mismatch",
  "stale_persisted_state",
  "unsupported_claim_strength"
] as const;

export const PROMOTION_CONFIRMATORY_INTERVAL_ALPHA = 0.05;
export const PROMOTION_CONFIRMATORY_INTERVAL_TAIL_PROBABILITY =
  PROMOTION_CONFIRMATORY_INTERVAL_ALPHA / 2;
export const PROMOTION_CONFIRMATORY_MAXIMUM_CONFLICT_RATE = 0.05;
export const PROMOTION_CONFIRMATORY_MINIMUM_CLEAN_PROMOTION_ACCURACY = 0.90;

export const MINIMUM_PROMOTION_PAPER_ELIGIBLE_BASE_BUNDLES = Math.ceil(
  Math.log(PROMOTION_CONFIRMATORY_INTERVAL_TAIL_PROBABILITY)
    / Math.log(1 - PROMOTION_CONFIRMATORY_MAXIMUM_CONFLICT_RATE)
);
export const MINIMUM_PROMOTION_CLEAN_SUCCESS_BASE_BUNDLES = Math.ceil(
  Math.log(PROMOTION_CONFIRMATORY_INTERVAL_TAIL_PROBABILITY)
    / Math.log(PROMOTION_CONFIRMATORY_MINIMUM_CLEAN_PROMOTION_ACCURACY)
);
export const PROMOTION_CONFIRMATORY_VARIANTS_PER_BASE =
  REQUIRED_CONFIRMATORY_MUTATION_FAMILIES.length + 1;
export const MINIMUM_PROMOTION_PAPER_ELIGIBLE_CASES =
  MINIMUM_PROMOTION_PAPER_ELIGIBLE_BASE_BUNDLES * PROMOTION_CONFIRMATORY_VARIANTS_PER_BASE;
